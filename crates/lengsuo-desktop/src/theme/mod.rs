//! 设计令牌与交互语义（跨端可复用的**语义层**，无渲染）。
//!
//! 本模块只定义「什么颜色 / 什么标题」，不定义「怎么画」。
//! 换成任何渲染后端（GPUI / 其他）都复用本层。
//!
//! 内容分工：
//! - [`colors`]：颜色语义令牌，亮/暗两套，**涨红跌绿**（见 `colors` 模块文档）。
//! - [`tokens`]：间距 / 字号 / 圆角尺寸令牌 + 主题切换。
//! - [`palette`]：**不是**颜色调色板，是命令面板的命令表（命名有歧义，
//!   待主理人后续移出 `theme/`；本卡不动它）。
//! - [`tool_titles`]：工具名人话映射。

/// 颜色调色板（语义色 + 亮暗两套）。
pub mod colors;

/// 尺寸令牌与主题切换。
pub mod tokens;

pub mod palette;
pub mod tool_titles;
